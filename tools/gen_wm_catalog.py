REGION_ORDER = ["Nature", "Oceans", "Europe", "Americas", "Asia-Pacific", "Middle East", "Space"]


def cams():
    import re
    with urllib.request.urlopen(CAMS_SRC, timeout=30) as r:
        ts = r.read().decode("utf-8")
    block = ts[ts.index("export const WEBCAM_SOURCES"):]
    block = block[:block.index("} as const")]
    rows = []
    for m in re.finditer(r"^\s*'?([a-z-]+)'?:\s*\[(.*?)\]", block, re.M | re.S):
        slot, body = m.group(1), m.group(2)
        ids = re.findall(r"watch\?v=([\w-]{11})", body)
        if not ids or slot not in CAM_INFO:
            continue  # empty slot (no working stream today) or one Glow has no label for yet
        title, detail, region, lat, lon = CAM_INFO[slot]
        rows.append([slot, title, detail, region, str(lat), str(lon)] + MORE_STREAMS.get(slot, []) + ids)
    rows += [[str(x) for x in row] for row in MORE_CAMS]
    rows.sort(key=lambda r: REGION_ORDER.index(r[3]))  # (stable: the order within a region stays)
    body = ",\n".join("            {" + ", ".join(java(x) for x in row) + "}" for row in rows)
    CAMS_OUT.write_text(f"""package com.tv98.glow;

/**
 * GENERATED by tools/gen_wm_catalog.py from World Monitor's webcam list (live-video-sources.ts) and Glow's additions — don't edit by hand.
 * Each row: {{slot, title, detail, region, latitude ("" = none), longitude, YouTube live video ids...}}.
 */
final class WmCams {{
    static final String[][] CAMS = {{
{body}
    }};

    private WmCams() {{}}
}}
""")
    print(f"wrote {CAMS_OUT.name}: {len(rows)} webcams")


