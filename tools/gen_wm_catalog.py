"""Generates src/com/tv98/glow/WmCatalog.java from World Monitor's live-TV catalogue.

The catalogue (koala73/worldmonitor, cli/src/tui/data/catalog.generated.json) lists ~90 news channels with
their official stream links and YouTube channel ids. Glow uses it for extra backup links and to find a
channel's official YouTube live stream. Re-run when the catalogue changes:

    python3 tools/gen_wm_catalog.py
"""
import json
import pathlib
import urllib.request

SRC = "https://raw.githubusercontent.com/koala73/worldmonitor/HEAD/cli/src/tui/data/catalog.generated.json"
OUT = pathlib.Path(__file__).resolve().parent.parent / "src/com/tv98/glow/WmCatalog.java"


def java(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    with urllib.request.urlopen(SRC, timeout=30) as r:
        catalog = json.load(r)
    rows = []
    for ch in catalog["channels"]:
        channel_id = ""
        streams = []
        for s in ch.get("sources", []):
            if "/channel/UC" in s:
                channel_id = s.split("/channel/")[1].split("/")[0].split("?")[0]
            elif ".m3u8" in s:
                streams.append(s)
        if channel_id or streams:
            rows.append([ch["name"], ch.get("region", ""), channel_id] + streams)
    body = ",\n".join("            {" + ", ".join(java(x) for x in row) + "}" for row in rows)
    OUT.write_text(f"""package com.tv98.glow;

/**
 * GENERATED by tools/gen_wm_catalog.py from World Monitor's live-TV catalogue — don't edit by hand.
 * Each row: {{name, region (na/eu/asia/me/latam/africa/oc), official YouTube channel id (or ""), official stream links...}}.
 */
final class WmCatalog {{
    static final String[][] CHANNELS = {{
{body}
    }};

    private WmCatalog() {{}}
}}
""")
    print(f"wrote {OUT.name}: {len(rows)} channels")
    cams()


